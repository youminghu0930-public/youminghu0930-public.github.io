import { readFile, writeFile, access } from 'node:fs/promises';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const args = process.argv.slice(2);
const personalIndex = args.indexOf('--personal');
if (personalIndex !== -1 && !args[personalIndex + 1]) throw new Error('--personal requires a checkout path');
const theme = JSON.parse(await readFile(new URL('../design/theme.json', import.meta.url), 'utf8'));
if (theme.version !== 1) throw new Error('Unsupported design version');
const template = await readFile(new URL('../design/styles.template.css', import.meta.url), 'utf8');
const css = '/* Generated by scripts/sync-design.mjs in main-public.github.io. Edit design/ sources there. */\n' + template.replace(/\{\{(\w+)\}\}/g, (_, key) => {
  if (typeof theme.tokens[key] !== 'string') throw new Error(`Missing design token: ${key}`);
  return theme.tokens[key];
});
const targets = [resolve(root, 'styles.css')];
if (!args.includes('--local')) targets.push(resolve(personalIndex === -1 ? resolve(root, '../../Private/main-private.github.io') : args[personalIndex + 1], 'styles.css'));
for (const target of targets) {
  await access(resolve(dirname(target), 'main.js'));
  await access(target);
}
let drift = false;
for (const target of targets) {
  if (args.includes('--check')) {
    if (await readFile(target, 'utf8') !== css) {
      console.error(`Design differs: ${target}. Run node scripts/sync-design.mjs.`);
      drift = true;
    }
  } else await writeFile(target, css);
}
if (drift) process.exitCode = 1;
else console.log(args.includes('--check') ? 'Shared design matches.' : 'Shared design synchronized.');
