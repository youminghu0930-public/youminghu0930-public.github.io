import {readFile} from 'node:fs/promises';
import assert from 'node:assert/strict';
import test from 'node:test';
const moduleFrom=async path=>import(`data:text/javascript;base64,${Buffer.from(await readFile(new URL(path,import.meta.url),'utf8')).toString('base64')}`);
const {collideOrnaments,createOrnamentCollisionWorld}=await moduleFrom('../materials/data/ornament-collisions.js');
const {installOrnamentDrag}=await moduleFrom('../materials/data/ornament-drag.js');
const body=(x,vx,vy=0,inverseMass=1)=>({x,y:0,vx,vy,inverseMass,radius:20});
test('marble impacts conserve momentum, lose some energy, and preserve tangential motion',()=>{
  const [a,b]=collideOrnaments(body(0,100,30),body(39,0,30));
  assert(Math.abs(a.vx+b.vx-100)<1e-8);
  assert(b.vx>80&&a.vx<20);
  assert(a.vx*a.vx+b.vx*b.vx<10000);
  assert.equal(a.vy,30);assert.equal(b.vy,30);
  const held=collideOrnaments(body(0,100,0,0),body(39,0));
  assert(Math.abs(held[0].dx)<1e-8);assert(held[1].vx>100);
  const separating=collideOrnaments(body(0,-100),body(39,100));
  assert.equal(separating[0].vx,-100);assert.equal(separating[1].vx,100);
  assert.equal(collideOrnaments(body(0,100),body(100,0)),null);
});
test('complete wrappers exchange momentum and scroll response varies with height',()=>{
  let now=0,next=0,areaTop=0;const frames=new Map(),windowEvents=new Map();
  Object.defineProperty(globalThis,'performance',{configurable:true,value:{now:()=>now}});
  globalThis.requestAnimationFrame=f=>{frames.set(++next,f);return next};
  globalThis.cancelAnimationFrame=id=>frames.delete(id);
  globalThis.matchMedia=()=>({matches:false,addEventListener(){}});
  globalThis.window={addEventListener(type,f){const list=windowEvents.get(type)||[];list.push(f);windowEvents.set(type,list)}};
  const wrapper=()=>({offsetWidth:40,style:{},dataset:{},events:new Map(),addEventListener(t,f){this.events.set(t,f)},setPointerCapture(){},hasPointerCapture(){return false}});
  const a=wrapper(),b=wrapper(),world=createOrnamentCollisionWorld();
  const options={getBounds:()=>({x:[0,1000],y:[0,600]}),getAreaTop:()=>areaTop,getRadius:()=>20,collisionWorld:world};
  const da=installOrnamentDrag({button:a,...options}),db=installOrnamentDrag({button:b,...options});
  const fire=(target,type,x,y,time)=>{now=time;const e={type,clientX:x,clientY:y,timeStamp:time,pointerId:1,isPrimary:true,pointerType:'mouse',button:0,preventDefault(){}};if(target)target.events.get(type)(e);else for(const f of windowEvents.get(type)||[])f(e)};
  const step=()=>{now+=1000/120;const pending=[...frames.values()];frames.clear();pending.forEach(f=>f(now))};
  const x=e=>parseFloat(e.style.translate),y=e=>parseFloat(e.style.translate.split(' ')[1]);
  da.draw(100,100);db.draw(300,100);
  fire(a,'pointerdown',100,100,0);fire(null,'pointermove',200,100,100);fire(null,'pointerup',200,100,100);
  for(let i=0;i<60;i++)step();
  assert(x(b)>330,'struck ornament must receive momentum and move');
  assert(x(b)-x(a)>=39,'ornaments must separate after impact');
  da.destroy();db.destroy();
  // New world, with one ornament near the ceiling and one near the floor.
  windowEvents.clear();frames.clear();
  const top=wrapper(),bottom=wrapper();
  const dt=installOrnamentDrag({button:top,...options,collisionWorld:null});
  const df=installOrnamentDrag({button:bottom,...options,collisionWorld:null});
  dt.draw(100,50);df.draw(500,500);areaTop=-20;
  for(const f of windowEvents.get('scroll'))f();
  assert(y(bottom)-500>y(top)-50,'lower ornament should have broader scroll lag');
  for(let i=0;i<1200;i++)step();
  assert(Math.abs(y(top)-50)<.1&&Math.abs(y(bottom)-500)<.1,'both height-dependent springs must settle');
  dt.destroy();df.destroy();
});
