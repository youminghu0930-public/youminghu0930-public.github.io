import {readFile} from 'node:fs/promises';
import assert from 'node:assert/strict';
import test from 'node:test';
const source=await readFile(new URL('../materials/data/ornament-impact.js',import.meta.url),'utf8');
const {installOrnamentImpact}=await import(`data:text/javascript;base64,${Buffer.from(source).toString('base64')}`);
test('wall sparks stay at contact while ornament collision sparks follow the wrapper',()=>{
  let now=100;
  Object.defineProperty(globalThis,'performance',{configurable:true,value:{now:()=>now}});
  globalThis.matchMedia=()=>({matches:false});
  const node=()=>({style:{},children:[],animations:[],offsetWidth:88,setAttribute(){},append(child){this.children.push(child);child.parent=this},remove(){this.removed=true},getAnimations(){return this.children.flatMap(child=>child.animations)},animate(keyframes,options){const animation={keyframes,options,finished:new Promise(()=>{}),cancel(){}};this.animations.push(animation);return animation}});
  globalThis.document={hidden:false,timeline:{currentTime:100},createElement:node};
  const scene=node(),wrapper=node();scene.append(wrapper);
  const effect=installOrnamentImpact(wrapper,scene);
  effect.trigger({kind:'wall',impactTime:96,speed:1000,nx:1,ny:0,x:600,y:200});
  const wall=scene.children[1];
  assert.equal(wall.style.left,'600px');assert.equal(wall.style.top,'200px');
  assert(wall.children.length>=20,'strong impact must show a clear particle burst');
  assert(wall.children.every(child=>child.animations[0].startTime===96),'all particles must start on the physics impact timestamp');
  assert(wall.children.every(child=>child.animations[0].options.duration<=640),'impact burst should finish within its extended fade');
  assert(wall.children.every(child=>child.animations[0].options.fill==='forwards'&&child.animations[0].keyframes.at(-1).opacity===0),'finished particles must remain invisible until cleanup');
  assert(new Set(wall.children.slice(1).map(child=>child.style.width)).size>5,'particle lengths should vary rather than form uniform confetti');
  wrapper.style.translate='200px 100px';
  assert.equal(wall.style.left,'600px','wall contact must not follow the ornament');
  const path=wall.children[1].animations[0].keyframes;
  assert(path.length>=15,'particles need a sampled curved trajectory');
  const headings=path.map(frame=>Number(frame.transform.match(/rotate\(([-\d.]+)rad/)[1]));
  assert(Math.max(...headings)-Math.min(...headings)>.2,'particles must change heading as they wander');
  const lastFrame=path.at(-1).transform;
  assert.match(lastFrame,/translate\(-/,'right-wall particles must spray inward');
  now=200;effect.trigger({kind:'ornament',speed:800,nx:1,ny:0});
  assert.equal(wrapper.children.length,1,'ornament collision burst must attach to its moving wrapper');
  effect.destroy();assert(wall.removed&&wrapper.children[0].removed,'both kinds of bursts must be cleaned up');
});
